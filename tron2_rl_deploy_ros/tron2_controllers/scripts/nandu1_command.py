#!/usr/bin/env python3
"""Task-selected atomic external intents; keyboard or small-step experiment."""
import argparse
import os
import select
import sys
import termios
import tty
import time
import json
import rospy
from tron2_controllers.msg import NANDU1Command
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[3]/'tron2_mujoco_sim'))
import nandu1_contract as contract
from nandu1_adaptive_contract import deployment_profile,adaptive_tasks

def command_interface(task):
    from nandu1_mouse_protocol import command_interface as interface
    return interface(task)

def assign_command(msg,family,values):
    if family=='heading':msg.relative_heading_rate,msg.up3_vx_base_heading,msg.up3_height_world=values
    elif family=='tcp':msg.relative_heading_rate,msg.tcp_vx_base_body,msg.tcp_height_world=values
    else:msg.yaw_rate_world_z,msg.up3_vx_base_body,msg.up3_height_world=values

def read_keyboard_byte(fd):
    # TextIOWrapper may prefetch a second key into its own buffer, invisible
    # to select(); read the descriptor directly so key bursts aren't delayed.
    return os.read(fd,1).decode(errors='ignore').lower()

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--mode',choices=['keyboard','steps','lifecycle'],default='keyboard')
    parser.add_argument('--height',type=float,default=.88564531185)
    parser.add_argument('--task',choices=contract.TASKS+contract.PLAY_ALIASES+contract.NETWORK_TASKS+contract.NETWORK_PLAY_ALIASES+adaptive_tasks(include_play=True),default=contract.TASK)
    args=parser.parse_args(rospy.myargv()[1:])
    rospy.init_node('nandu1_command')
    family,topic=command_interface(args.task);v14=family=='heading'
    profile=deployment_profile(args.task)
    if rospy.get_param('/model_bundle/task/task_id','')!=profile['task_id']:raise RuntimeError('Command task differs from the validated running bundle')
    lower=rospy.get_param('/model_bundle/task/command_min');upper=rospy.get_param('/model_bundle/task/command_max')
    owner=rospy.get_param('/nandu1/mouse_owner',None)
    if owner is not None:
        import rosgraph
        from nandu1_mouse_protocol import assert_external_available
        assert_external_available(owner,rosgraph.Master(rospy.get_name()).getSystemState()[0])
    if v14:
        from tron2_controllers.msg import NANDU1V14Command
        message_type=NANDU1V14Command
    elif family=='tcp':
        from tron2_controllers.msg import NANDU1TCPCommand
        message_type=NANDU1TCPCommand
    else:message_type=NANDU1Command
    pub=rospy.Publisher(topic,message_type,queue_size=1)
    if args.mode=='lifecycle':
        from std_msgs.msg import String
        mode=rospy.Publisher('/nandu1/set_mode',String,queue_size=1)
        deadline=time.monotonic()+5
        while not (pub.get_num_connections() and mode.get_num_connections()):
            if time.monotonic()>deadline:raise RuntimeError('Controller command/mode subscribers unavailable')
            time.sleep(.02)
        def send(vx):
            msg=message_type();msg.header.stamp=rospy.Time.now();assign_command(msg,family,[0,vx,args.height])
            pub.publish(msg)
        end=time.monotonic()+1
        while time.monotonic()<end:send(.05);time.sleep(.02)
        last_publish=time.time();time.sleep(1)
        reset_stamp=time.time();mode.publish(String(data='RESET'))
        end=time.monotonic()+2
        while time.monotonic()<end:send(0);time.sleep(.02)
        print(json.dumps({'expiry_last_publish_wall':last_publish,'controller_reset_wall':reset_stamp}),flush=True)
        return
    values=[0.,0.,args.height]
    # Hold 60 s, then +/- longitudinal velocity, +/- yaw, +/- height, combination.
    segments=[(60,[0,0,args.height]),(5,[0,.1,args.height]),(5,[0,-.1,args.height]),
              (5,[.2,0,args.height]),(5,[-.2,0,args.height]),(5,[0,0,args.height+.05]),
              (5,[0,0,args.height-.05]),(5,[.1,.05,args.height]),(5,[0,0,args.height])]
    old=None;start=time.monotonic()
    if args.mode=='keyboard':
        old=termios.tcgetattr(sys.stdin);tty.setcbreak(sys.stdin)
        print('W/S: up3 longitudinal speed +/-0.05; A/D: yaw +/-0.1; Q/E: height +/-0.02; Space: zero speed; X: exit',flush=True)
        if v14:print('Velocity in base heading; yaw is relative-heading intent (zero holds heading); six command features generated by the selected controller.',flush=True)
        if family=='tcp':print('v1.3.1: TCP velocity in base body; absolute TCP height; zero yaw intent holds heading.',flush=True)
        print('Active bundle limits:',lower,upper,flush=True)
    try:
        while not rospy.is_shutdown():
            if args.mode=='keyboard':
                if select.select([sys.stdin],[],[],0)[0]:
                    key=read_keyboard_byte(sys.stdin.fileno())
                    if key=='x':break
                    if key in 'ws':values[1]+=.05 if key=='w' else -.05
                    if key in 'ad':values[0]+=.1 if key=='a' else -.1
                    if key in 'qe':values[2]+=.02 if key=='q' else -.02
                    if key==' ':values[:2]=[0.,0.]
            else:
                elapsed=time.monotonic()-start
                chosen=None
                for duration,v in segments:
                    if elapsed<duration:chosen=v;break
                    elapsed-=duration
                if chosen is None:break
                values=list(chosen)
            values=[max(lo,min(hi,value)) for value,lo,hi in zip(values,lower,upper)]
            msg=message_type();msg.header.stamp=rospy.Time.now()
            assign_command(msg,family,values)
            pub.publish(msg);time.sleep(.02)
    finally:
        if old is not None:termios.tcsetattr(sys.stdin,termios.TCSADRAIN,old)
        msg=message_type();assign_command(msg,family,[0,0,values[2]]);pub.publish(msg)

if __name__=='__main__':main()
